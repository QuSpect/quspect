# =============================================================================
# Helpers
# =============================================================================


def _export(circuit: QuantumCircuit, **kwargs) -> str:
    """Shortcut: export circuit with STRICT config."""
    config = QASM2ExportConfig(**kwargs)
    return QASM2Exporter(config).export(circuit)


